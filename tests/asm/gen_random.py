#!/usr/bin/env python3
"""Constrained-random RV32I program generator.

Emits straight-line code with forward-only branches/jumps (always terminating),
safe memory accesses into 0..0x3FF, and a fixed epilogue that stores x31 to
the magic signature address. Expected values come from tests/asm/iss.py.
"""
import argparse
import random

REGS = list(range(1, 32))  # never write x0


def gen(seed: int, n_instrs: int) -> str:
    rng = random.Random(seed)
    lines = ['# generated by gen_random.py', f'# seed: {seed}',
             '.text', '.globl _start', '_start:']
    for r in REGS:
        lines.append(f'\taddi x{r}, x0, {rng.randint(-2048, 2047)}')

    counter = [0]

    def label():
        counter[0] += 1
        return f'L{counter[0]}'

    def alu():
        kind = rng.random()
        d, a, b = (rng.choice(REGS) for _ in range(3))
        if kind < 0.35:
            op = rng.choice(['add', 'sub', 'and', 'or', 'xor',
                             'sll', 'srl', 'sra', 'slt', 'sltu'])
            lines.append(f'\t{op} x{d}, x{a}, x{b}')
        elif kind < 0.75:
            op = rng.choice(['addi', 'andi', 'ori', 'xori', 'slti', 'sltiu'])
            lines.append(f'\t{op} x{d}, x{a}, {rng.randint(-2048, 2047)}')
        else:
            op = rng.choice(['slli', 'srli', 'srai'])
            lines.append(f'\t{op} x{d}, x{a}, {rng.randint(0, 31)}')

    def mem():
        if rng.random() < 0.5:
            op = rng.choice(['lw', 'lh', 'lhu', 'lb', 'lbu'])
            size = 4 if op == 'lw' else (2 if op in ('lh', 'lhu') else 1)
            off = rng.randrange(0, 0x400 - size + 1)
            off -= off % size
            lines.append(f'\t{op} x{rng.choice(REGS)}, {off}(x0)')
        else:
            op = rng.choice(['sw', 'sh', 'sb'])
            size = 4 if op == 'sw' else (2 if op == 'sh' else 1)
            off = rng.randrange(0, 0x400 - size + 1)
            off -= off % size
            lines.append(f'\t{op} x{rng.choice(REGS)}, {off}(x0)')

    def branch():
        lab = label()
        cond = rng.choice(['beq', 'bne', 'blt', 'bge', 'bltu', 'bgeu'])
        a, b = rng.choice(REGS), rng.choice(REGS)
        lines.append(f'\t{cond} x{a}, x{b}, {lab}')
        for _ in range(rng.randint(1, 4)):
            alu()
        lines.append(f'{lab}:')

    def jump():
        lab = label()
        lines.append(f'\tjal x0, {lab}')
        for _ in range(rng.randint(1, 3)):
            alu()
        lines.append(f'{lab}:')

    for _ in range(n_instrs):
        c = rng.random()
        if c < 0.55:
            alu()
        elif c < 0.75:
            mem()
        elif c < 0.90:
            branch()
        else:
            jump()

    lines += ['\tlui x1, 0xFFFF0',
              '\tsw x31, 0(x1)',
              '\tj .']
    return '\n'.join(lines) + '\n'


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--seed', type=int, required=True)
    p.add_argument('--instrs', type=int, default=50)
    p.add_argument('--out', required=True)
    a = p.parse_args()
    with open(a.out, 'w') as f:
        f.write(gen(a.seed, a.instrs))
    print(f'wrote {a.out} (seed={a.seed})')


if __name__ == '__main__':
    main()
